import { execFile } from "node:child_process";
import { promisify } from "node:util";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const execute = promisify(execFile);
const directory = path.dirname(fileURLToPath(import.meta.url));
const docs = path.resolve(directory, "../docs");
const output = path.join(directory, "out");
await fs.mkdir(output, { recursive: true });
await fs.mkdir(docs, { recursive: true });
const input = path.join(docs, "demo.mp4");
const palette = path.join(output, "palette.png");
const gif = path.join(docs, "demo.gif");
await execute("ffmpeg", ["-y", "-i", input, "-vf", "fps=8,scale=640:-1:flags=lanczos,palettegen=max_colors=128", palette]);
await execute("ffmpeg", ["-y", "-i", input, "-i", palette, "-lavfi", "fps=8,scale=640:-1:flags=lanczos [x]; [x][1:v] paletteuse=dither=bayer:bayer_scale=5", gif]);
const { size } = await fs.stat(gif);
if (size > 8 * 1024 * 1024) throw new Error(`README GIF exceeds 8 MiB (${size} bytes). Shorten the footage before publishing.`);
console.log(`Saved ${gif} (${(size / 1024 / 1024).toFixed(2)} MiB)`);
